import java.util.*;

public class Solution {
    public int solution(int n) {
        int ans = 0;

        // 6/2=3; 3-1=2; 2/2=1; 1-1=0; (2)
        // 5-1=4; 4/2=2; 2/2=1; 1-1=0; (2)
        // 5000/2=2500; 2500/2=1250; 1250/2=625; 625-1=624;
        // 624/2=312; 312/2=156; 156/2=78; 78/2=39; 39-1=38;
        // 38/2=19; 19-1=18;
        // 18/2=9; 9-1=8;
        // 8/2=4; 4/2=2; 2/2=1; 1-1=0; (5)
        
        while(n>0){
            if(n%2==0){
                n/=2;
            }else{
                n-=1;
                ans++;
            }
        }

        return ans;
    }
}
